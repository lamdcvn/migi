#!/usr/bin/env python3
"""Generate a PHP file that registers a shortcode AND its Flatsome UX Builder element.

  python3 fs_scaffold_element.py spec.json > includes/ux-element-<tag>.php

spec.json (see ../templates/element/spec.example.json):
{
  "tag": "mg_counter", "name": "Đếm số", "category": "Migi", "prefix": "mg", "text_domain": "mg-motion",
  "container": false, "allow": [], "thumbnail_svg": "<svg …>",
  "options": [ {"key": "to", "type": "textfield", "heading": "Số", "default": "1000"}, … ],
  "groups":  { "Hiển thị": ["suffix", "label"] }      # optional collapsible groups
}
The generated render function is a stub that escapes every attribute – replace the markup.
"""
import json
import sys

TYPES = {'textfield', 'textarea', 'text-editor', 'select', 'radio-buttons', 'checkbox', 'slider', 'scrubfield', 'margins',
         'colorpicker', 'image', 'gallery', 'col-slider'}


def php(v, ind=0):
    pad = '\t' * ind
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if v is None:
        return "''"
    if isinstance(v, list):
        if not v:
            return 'array()'
        return 'array( ' + ', '.join(php(x) for x in v) + ' )'
    if isinstance(v, dict):
        if not v:
            return 'array()'
        rows = [f"{pad}\t{php(k)} => {php(x, ind + 1)}," for k, x in v.items()]
        return 'array(\n' + '\n'.join(rows) + f'\n{pad})'
    return "'" + str(v).replace('\\', '\\\\').replace("'", "\\'") + "'"


def option(o):
    if o.get('type') not in TYPES:
        raise SystemExit(f'Unknown option type "{o.get("type")}" for "{o.get("key")}" (allowed: {", ".join(sorted(TYPES))})')
    d = {k: v for k, v in o.items() if k != 'key'}
    if o['type'] in ('select', 'radio-buttons') and isinstance(o.get('options'), list):
        d['options'] = {x: ({'title': x} if o['type'] == 'radio-buttons' else x) for x in o['options']}
    if o['type'] == 'checkbox' and 'default' in d:
        d['default'] = 'true' if d['default'] in (True, 'true', '1', 1) else 'false'
    return d


def main(path):
    s = json.load(open(path, encoding='utf-8'))
    tag, prefix = s['tag'], s.get('prefix', 'mg')
    fn = tag.replace('-', '_')
    td = s.get('text_domain', prefix)
    opts = {o['key']: option(o) for o in s.get('options', [])}
    groups = s.get('groups') or {}
    grouped = set(k for keys in groups.values() for k in keys)
    ux_opts = {k: v for k, v in opts.items() if k not in grouped}
    for title, keys in groups.items():
        ux_opts['group_' + ''.join(c for c in title.lower() if c.isalnum())[:20]] = {
            'type': 'group', 'heading': title, 'options': {k: opts[k] for k in keys if k in opts}}
    ux_opts['advanced_options'] = {'type': 'group', 'heading': 'Advanced', 'options': {
        'class': {'type': 'textfield', 'heading': 'Class', 'default': ''},
        'visibility': {'type': 'select', 'heading': 'Visibility', 'default': '', 'options': {
            '': 'Visible', 'hidden': 'Hidden', 'hide-for-medium': 'Only for Desktop', 'show-for-small': 'Only for Mobile',
            'show-for-medium hide-for-small': 'Only for Tablet', 'show-for-medium': 'Hide for Desktop', 'hide-for-small': 'Hide for Mobile'}},
    }}
    defaults = {k: str(v.get('default', '')) for k, v in opts.items()}
    defaults.update({'class': '', 'visibility': ''})
    reg = {'name': s.get('name', tag), 'category': s.get('category', 'Migi'), 'wrap': False, 'priority': s.get('priority', 10)}
    if s.get('container'):
        reg['type'] = 'container'
    if s.get('allow'):
        reg['allow'] = s['allow']
    if s.get('require'):
        reg['require'] = s['require']
    if s.get('info'):
        reg['info'] = s['info']
    svg = s.get('thumbnail_svg') or ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 68"><rect width="100" height="68" rx="8" fill="#fff4e5"/>'
                                     '<rect x="34" y="18" width="32" height="32" rx="9" fill="#ff8a00"/></svg>')
    out = f"""<?php
/**
 * [{tag}] shortcode + Flatsome UX Builder element "{reg['name']}".
 * Generated by fs_scaffold_element.py – edit the render function, keep option keys in sync with the defaults.
 */
defined( 'ABSPATH' ) || exit;

function {fn}_defaults() {{
	return {php(defaults, 1)};
}}

/** Front-end output (works with or without Flatsome). */
function {fn}_render( $atts, $content = '' ) {{
	$a       = shortcode_atts( {fn}_defaults(), $atts, '{tag}' );
	$classes = trim( '{tag.replace('_', '-')} ' . $a['class'] . ' ' . $a['visibility'] );
	ob_start();
	?>
	<div class="<?php echo esc_attr( $classes ); ?>">
		<?php /* TODO: markup. Escape every attribute: esc_html( $a['…'] ), esc_url(), esc_attr(). */ ?>
		{'<?php echo do_shortcode( $content ); // phpcs:ignore -- child elements. ?>' if s.get('container') else ''}
	</div>
	<?php
	return ob_get_clean();
}}
add_shortcode( '{tag}', '{fn}_render' );

/** UX Builder element (only when Flatsome's builder loads). */
add_action( 'ux_builder_setup', function () {{
	if ( ! function_exists( 'add_ux_builder_shortcode' ) ) {{
		return;
	}}
	add_ux_builder_shortcode( '{tag}', array_merge( {php(reg, 1)}, array(
		'thumbnail' => 'data:image/svg+xml;base64,' . base64_encode( {php(svg)} ),
		'options'   => {php(ux_opts, 2)},
	) ) );
}} );
"""
    sys.stdout.write(out)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1])
